// Tests the two global git hooks: their rules directly, then through real git commands in throwaway repos.
// Run with: node --test

import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";

import { isConventional, refusedWhenCreating, refusedWhenPushing } from "../.git-hooks/branch-name-rule.mjs";
import { withoutAiCredit } from "../.git-hooks/strip-ai-attribution.mjs";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const NO_COMMIT = "0".repeat(40);
const SOME_COMMIT = "1".repeat(40);

describe("AI credit", () => {
  const stripped = [
    "Co-Authored-By: Claude Sonnet 4.6 <noreply@anthropic.com>",
    "Co-Authored-By: GitHub Copilot <copilot@github.com>",
    "Co-Authored-By: ChatGPT <chatgpt@openai.com>",
    "Co-Authored-By: Cursor <cursor@cursor.sh>",
    "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
    "Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>",
    "Generated by Codex",
    "generated by claude code",
    "🤖 Generated with [Claude Code](https://claude.ai/code)",
    "_Generated using Cursor_",
    "Generated by GPT-5",
  ];

  const kept = [
    "fix: remove files generated by codex",
    "The schema is generated by the Codex tool",
    "Generated by protoc",
    "Co-Authored-By: Alice <alice@example.com>",
    "Co-Authored-By: Haider Ali <haider@example.com>",
    "Co-Authored-By: Devin Smith <devin@example.com>",
    "Co-Authored-By: Claude Monet <claude@example.com>",
    "Co-Authored-By: Alice <alice@sourcegraph.com>",
  ];

  for (const line of stripped) {
    test(`removes: ${line}`, () => {
      assert.equal(withoutAiCredit(`feat: x\n\n${line}\n`), "feat: x\n\n");
    });
  }

  for (const line of kept) {
    test(`keeps: ${line}`, () => {
      assert.equal(withoutAiCredit(`feat: x\n\n${line}\n`), `feat: x\n\n${line}\n`);
    });
  }

  test("keeps a message that would end up empty", () => {
    assert.equal(withoutAiCredit("Generated by Codex"), "Generated by Codex");
  });
});

describe("branch names", () => {
  for (const name of ["feat/782-analytics", "fix/login-retry", "chore/bump", "docs/plan", "refactor/a.b", "test/x",
    "prototype/some-spike", "research/some-question"]) {
    test(`allows ${name}`, () => assert.ok(isConventional(name)));
  }

  for (const name of ["codex/x", "my-branch", "feature/x", "fix/Login", "fix/"]) {
    test(`refuses ${name}`, () => assert.ok(!isConventional(name)));
  }

  test("creating: allows main, worktree-* and branches GitHub already has", () => {
    const input = ["main", "worktree-agent-a4", "dependabot/npm-x", "codex/y"]
      .map((name) => `${NO_COMMIT} ${SOME_COMMIT} refs/heads/${name}`)
      .join("\n");

    assert.deepEqual(refusedWhenCreating(input, (name) => name === "dependabot/npm-x"), ["codex/y"]);
  });

  test("creating: ignores updates, deletions and tags", () => {
    const input = [
      `${SOME_COMMIT} ${SOME_COMMIT} refs/heads/codex/updated`,
      `${SOME_COMMIT} ${NO_COMMIT} refs/heads/codex/deleted`,
      `${NO_COMMIT} ${SOME_COMMIT} refs/tags/v1`,
    ].join("\n");

    assert.deepEqual(refusedWhenCreating(input, () => false), []);
  });

  test("pushing: refuses a new worktree-* branch, allows updates", () => {
    const input = [
      `refs/heads/worktree-a ${SOME_COMMIT} refs/heads/worktree-a ${NO_COMMIT}`,
      `refs/heads/fix/a ${SOME_COMMIT} refs/heads/fix/a ${NO_COMMIT}`,
      `refs/heads/codex/old ${SOME_COMMIT} refs/heads/codex/old ${SOME_COMMIT}`,
    ].join("\n");

    assert.deepEqual(refusedWhenPushing(input), ["worktree-a"]);
  });
});

describe("through git, with this repo's .gitconfig and hooks", () => {
  const root = mkdtempSync(join(tmpdir(), "dotfiles-hooks-"));
  const home = join(root, "home");
  mkdirSync(home);
  symlinkSync(join(REPO, ".gitconfig"), join(home, ".gitconfig"));
  symlinkSync(join(REPO, ".git-hooks"), join(home, ".git-hooks"));
  after(() => rmSync(root, { recursive: true, force: true }));

  const environment = { ...process.env, HOME: home, GIT_CONFIG_NOSYSTEM: "1" };
  delete environment.CLAUDE_CODE_SESSION_ID;
  delete environment.GIT_CONFIG_GLOBAL;

  const git = (repo, ...args) => spawnSync("git", ["-C", repo, ...args], { env: environment, encoding: "utf8" });

  const newRepo = (name, originUrl) => {
    const repo = join(root, name);
    execFileSync("git", ["init", "-q", "-b", "main", repo], { env: environment });
    git(repo, "config", "user.name", "Test User");
    git(repo, "config", "user.email", "test@example.com");
    git(repo, "remote", "add", "origin", originUrl);
    git(repo, "commit", "-q", "--allow-empty", "-m", "first");
    return repo;
  };

  const own = newRepo("own", "https://github.com/maximsan/example.git");

  test("refuses a bad name through each command that creates a branch", () => {
    for (const args of [["switch", "-c", "codex/x"], ["checkout", "-b", "my-branch"], ["branch", "feature/x"]]) {
      const result = git(own, ...args);
      assert.notEqual(result.status, 0, args.join(" "));
      assert.match(result.stderr, /breaks the naming rule/);
    }
  });

  test("allows a conventional name", () => {
    assert.equal(git(own, "branch", "fix/login-retry").status, 0);
  });

  test("a rename skips the create check", () => {
    assert.equal(git(own, "branch", "fix/rename-me").status, 0);
    assert.equal(git(own, "branch", "-m", "fix/rename-me", "codex/renamed").status, 0);
  });

  test("covers a repo with its own hook folder, and still runs that repo's hook", () => {
    const husky = newRepo("husky", "git@github.com:maximsan/example.git");
    mkdirSync(join(husky, ".husky"));
    const ownHook = join(husky, ".husky", "commit-msg");
    writeFileSync(ownHook, `#!/bin/sh\necho ran > "${join(root, "own-hook-ran")}"\n`, { mode: 0o755 });
    git(husky, "config", "core.hooksPath", ".husky");

    assert.notEqual(git(husky, "branch", "codex/x").status, 0);
    git(husky, "commit", "-q", "--allow-empty", "-m", "feat: x\n\nGenerated by Codex\nCo-authored-by: Codex <codex@openai.com>");
    assert.doesNotMatch(git(husky, "log", "-1", "--format=%B").stdout, /codex/i);
    assert.equal(readFileSync(join(root, "own-hook-ran"), "utf8"), "ran\n");
  });

  test("without node on the PATH, git still works and the message keeps its credit", () => {
    const repo = newRepo("no-node", "https://github.com/maximsan/example.git");
    const withoutNode = { ...environment, PATH: "/usr/bin:/bin" };
    const gitWithoutNode = (...args) => spawnSync("/usr/bin/git", ["-C", repo, ...args], { env: withoutNode, encoding: "utf8" });

    assert.equal(gitWithoutNode("branch", "codex/x").status, 0);
    assert.equal(gitWithoutNode("commit", "-q", "--allow-empty", "-m", "feat: x\n\nGenerated by Codex").status, 0);
    assert.match(gitWithoutNode("log", "-1", "--format=%B").stdout, /Generated by Codex/);
  });

  test("packing refs doesn't refuse a branch that already exists", () => {
    assert.equal(git(own, "-c", "hook.branch-name-creating.enabled=false", "branch", "old-name").status, 0);
    assert.equal(git(own, "pack-refs", "--all").status, 0);
  });

  test("without the scripts linked, git still works", () => {
    const bare = join(root, "bare-home");
    mkdirSync(bare);
    symlinkSync(join(REPO, ".gitconfig"), join(bare, ".gitconfig"));
    const unlinked = { ...environment, HOME: bare };

    const repo = join(root, "unlinked");
    const gitUnlinked = (...args) => spawnSync("git", args, { env: unlinked, encoding: "utf8" });
    assert.equal(gitUnlinked("init", "-q", "-b", "main", repo).status, 0);
    gitUnlinked("-C", repo, "remote", "add", "origin", "https://github.com/maximsan/example.git");
    const commit = gitUnlinked("-C", repo, "-c", "user.name=Test User", "-c", "user.email=test@example.com", "commit",
      "-q", "--allow-empty", "-m", "feat: x");
    assert.equal(commit.status, 0, commit.stderr);
    assert.equal(gitUnlinked("-C", repo, "branch", "codex/x").status, 0);
  });

  test("leaves other people's repos and local origins alone", () => {
    assert.equal(git(newRepo("other", "https://github.com/someone/example.git"), "branch", "TICKET-123--x").status, 0);
    assert.equal(git(newRepo("local", "/tmp/elsewhere"), "branch", "whatever").status, 0);
  });
});
