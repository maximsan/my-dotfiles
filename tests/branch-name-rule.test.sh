#!/bin/sh
# Runs the global branch-name rule and attribution stripping against disposable repos.
unset CLAUDE_CODE_SESSION_ID
ROOT=$(mktemp -d)
trap 'rm -rf "$ROOT"' EXIT
fail() { echo "FAIL: $1"; exit 1; }

init_repo() {
  git init -q -b main "$1"
  git -C "$1" config user.name t
  git -C "$1" config user.email t@t
  git -C "$1" remote add origin "$2"
  git -C "$1" commit -q --allow-empty -m first
}

OWN="$ROOT/own"; init_repo "$OWN" https://github.com/maximsan/example.git

# Blocked names, through each route.
git -C "$OWN" switch -q -c codex/x 2>/dev/null && fail "switch -c codex/x allowed"
git -C "$OWN" checkout -q -b my-branch 2>/dev/null && fail "checkout -b my-branch allowed"
git -C "$OWN" branch feature/x 2>/dev/null && fail "branch feature/x allowed"
git -C "$OWN" worktree add -q -b codex/y "$ROOT/wt-y" 2>/dev/null && fail "worktree add -b codex/y allowed"
# A rename skips Git's reference-transaction event, so only the push check catches it.
git -C "$OWN" branch -q fix/rename-me || fail "fix/rename-me refused"
git -C "$OWN" branch -m fix/rename-me codex/renamed || fail "rename no longer skips the event: update the rule's comment"

# The message names the rule.
git -C "$OWN" branch codex/z 2>&1 | grep -q 'breaks the naming rule' || fail "message missing"

# Allowed names.
for name in feat/782-analytics fix/login-retry chore/bump docs/plan refactor/a.b test/x prototype/roasty-rive research/rive-roasty worktree-agent-a4a342; do
  git -C "$OWN" branch "$name" || fail "$name refused"
done

# A branch that already exists on GitHub can be checked out.
git -C "$OWN" update-ref refs/remotes/origin/dependabot/npm-x HEAD
git -C "$OWN" branch dependabot/npm-x || fail "existing remote branch refused"

# A repo with its own hooks path is still covered.
LOCAL="$ROOT/local"; init_repo "$LOCAL" git@github.com:maximsan/example.git
git -C "$LOCAL" config core.hooksPath .git/hooks
git -C "$LOCAL" branch codex/x 2>/dev/null && fail "own hooks path escaped the rule"
git -C "$LOCAL" commit -q --allow-empty -m "feat: x

Generated by Codex
Co-authored-by: Codex <codex@openai.com>"
git -C "$LOCAL" log -1 --format=%B | grep -qiE 'codex' && fail "own hooks path escaped stripping"

# Other people's repos and local fixtures are left alone.
OTHER="$ROOT/other"; init_repo "$OTHER" https://github.com/someone/example.git
git -C "$OTHER" branch CHECK-1040--anything || fail "another owner's repo was blocked"
FIXTURE="$ROOT/fixture"; init_repo "$FIXTURE" /tmp/elsewhere
git -C "$FIXTURE" branch whatever || fail "a local fixture was blocked"

# Push: a tool-made name is refused on the way to GitHub, others pass.
PUSH="$HOME/.git-hooks/branch-name-rule"
Z=0000000000000000000000000000000000000000; A=1111111111111111111111111111111111111111
U=https://github.com/maximsan/example.git
echo "refs/heads/worktree-a $A refs/heads/worktree-a $Z" | "$PUSH" pushing origin "$U" 2>/dev/null && fail "worktree-a pushed"
echo "refs/heads/fix/a $A refs/heads/fix/a $Z" | "$PUSH" pushing origin "$U" || fail "fix/a refused"
echo "refs/heads/codex/old $A refs/heads/codex/old $A" | "$PUSH" pushing origin "$U" || fail "update of an existing branch refused"
echo "refs/heads/worktree-a $A refs/heads/worktree-a $Z" | "$PUSH" pushing origin https://github.com/someone/x.git || fail "another owner's push refused"

# Attribution wording.
MSG="$ROOT/msg"; STRIP="$HOME/.git-hooks/strip-ai-attribution"
for line in 'Generated by Codex' 'generated by claude code' '🤖 Generated with [Claude Code](https://claude.ai/code)' '_Generated using Cursor_' 'Generated by GPT-5' 'Co-Authored-By: Claude <noreply@anthropic.com>'; do
  printf 'feat: x\n\n%s\n' "$line" > "$MSG"; "$STRIP" "$MSG"
  [ "$(grep -c . "$MSG")" = 1 ] || fail "not stripped: $line"
done
for line in 'fix: remove files generated by codex' 'The schema is generated by the Codex tool' 'Generated by protoc' 'Co-Authored-By: Alice <alice@example.com>'; do
  printf 'feat: x\n\n%s\n' "$line" > "$MSG"; "$STRIP" "$MSG"
  grep -qF "$line" "$MSG" || fail "wrongly stripped: $line"
done
echo "PASS: branch-name-rule"
