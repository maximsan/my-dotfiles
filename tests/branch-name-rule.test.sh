#!/bin/sh
# Runs the branch-name rule and attribution stripping against disposable repos.
# A temporary home folder links this repo's files, so the tracked versions are tested.
unset CLAUDE_CODE_SESSION_ID
REPO=$(cd "$(dirname "$0")/.." && pwd)
ROOT=$(mktemp -d)
trap 'rm -rf "$ROOT"' EXIT
export HOME="$ROOT/home"
mkdir "$HOME"
ln -s "$REPO/.gitconfig" "$HOME/.gitconfig"
ln -s "$REPO/.git-hooks" "$HOME/.git-hooks"
ln -s "$REPO/.git-template" "$HOME/.git-template"
fail() { echo "FAIL: $1"; exit 1; }

init_repo() {
  git init -q -b main "$1"
  git -C "$1" config user.name t
  git -C "$1" config user.email t@t
  git -C "$1" remote add origin "$2"
  git -C "$1" commit -q --allow-empty -m first
}

OWN="$ROOT/own"; init_repo "$OWN" https://github.com/maximsan/example.git

# Refused names, through each git command that creates a branch.
git -C "$OWN" switch -q -c codex/x 2>/dev/null && fail "switch -c codex/x allowed"
git -C "$OWN" checkout -q -b my-branch 2>/dev/null && fail "checkout -b my-branch allowed"
git -C "$OWN" branch feature/x 2>/dev/null && fail "branch feature/x allowed"
git -C "$OWN" worktree add -q -b codex/y "$ROOT/wt-y" 2>/dev/null && fail "worktree add -b codex/y allowed"
# A rename skips Git's reference-transaction hook, so only the push check catches it.
git -C "$OWN" branch -q fix/rename-me || fail "fix/rename-me refused"
git -C "$OWN" branch -m fix/rename-me codex/renamed || fail "rename no longer skips the hook: update the rule's comment"

# The message names the rule.
git -C "$OWN" branch codex/z 2>&1 | grep -q 'breaks the naming rule' || fail "message missing"

# Allowed names.
for name in feat/782-analytics fix/login-retry chore/bump docs/plan refactor/a.b test/x prototype/some-spike research/some-question worktree-agent-a4a342; do
  git -C "$OWN" branch "$name" || fail "$name refused"
done

# A branch that already exists on GitHub can be checked out.
git -C "$OWN" update-ref refs/remotes/origin/dependabot/npm-x HEAD
git -C "$OWN" branch dependabot/npm-x || fail "existing remote branch refused"

# A repo with its own hooks path is still covered.
LOCAL="$ROOT/local"; init_repo "$LOCAL" git@github.com:maximsan/example.git
git -C "$LOCAL" config core.hooksPath .git/hooks
git -C "$LOCAL" branch codex/x 2>/dev/null && fail "own hooks path bypassed the rule"
git -C "$LOCAL" commit -q --allow-empty -m "feat: x

Generated by Codex
Co-authored-by: Codex <codex@openai.com>"
git -C "$LOCAL" log -1 --format=%B | grep -qiE 'codex' && fail "own hooks path bypassed stripping"

# Other people's repos, and repos whose origin is a local path, are left alone.
OTHER="$ROOT/other"; init_repo "$OTHER" https://github.com/someone/example.git
git -C "$OTHER" branch TICKET-123--anything || fail "another owner's repo was refused"
FIXTURE="$ROOT/fixture"; init_repo "$FIXTURE" /tmp/elsewhere
git -C "$FIXTURE" branch whatever || fail "a repo with a local origin was refused"

# Push: a worktree-* name is refused on the way to GitHub, others pass.
PUSH="$HOME/.git-hooks/branch-name-rule"
NO_COMMIT=0000000000000000000000000000000000000000; SOME_COMMIT=1111111111111111111111111111111111111111
OWN_URL=https://github.com/maximsan/example.git
echo "refs/heads/worktree-a $SOME_COMMIT refs/heads/worktree-a $NO_COMMIT" | "$PUSH" pushing origin "$OWN_URL" 2>/dev/null && fail "worktree-a pushed"
echo "refs/heads/fix/a $SOME_COMMIT refs/heads/fix/a $NO_COMMIT" | "$PUSH" pushing origin "$OWN_URL" || fail "fix/a refused"
echo "refs/heads/codex/old $SOME_COMMIT refs/heads/codex/old $SOME_COMMIT" | "$PUSH" pushing origin "$OWN_URL" || fail "update of an existing branch refused"
echo "refs/heads/worktree-a $SOME_COMMIT refs/heads/worktree-a $NO_COMMIT" | "$PUSH" pushing origin https://github.com/someone/x.git || fail "another owner's push refused"

echo "PASS: branch-name-rule"
