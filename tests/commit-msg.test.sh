#!/bin/sh
# Runs the scripts tracked in this repo, not the installed ones.
HOOK="$(cd "$(dirname "$0")/.." && pwd)/.git-hooks/commit-msg"
# Inside Claude Code the hook adds a Claude-Session-Id line, which would break the unchanged-message check.
unset CLAUDE_CODE_SESSION_ID
TMPFILE=$(mktemp)

# Case 1: strips Claude
printf "feat: my commit\n\nCo-Authored-By: Claude Sonnet 4.6 <noreply@anthropic.com>\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
if grep -q "Co-Authored-By: Claude" "$TMPFILE"; then
  echo "FAIL: Claude Co-Authored-By was not removed"; rm "$TMPFILE"; exit 1
fi

# Case 2: strips GitHub Copilot
printf "feat: my commit\n\nCo-Authored-By: GitHub Copilot <copilot@github.com>\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
if grep -q "Co-Authored-By:.*[Cc]opilot" "$TMPFILE"; then
  echo "FAIL: Copilot Co-Authored-By was not removed"; rm "$TMPFILE"; exit 1
fi

# Case 3: strips ChatGPT
printf "feat: my commit\n\nCo-Authored-By: ChatGPT <chatgpt@openai.com>\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
if grep -q "Co-Authored-By:.*[Cc]hat[Gg][Pp][Tt]" "$TMPFILE"; then
  echo "FAIL: ChatGPT Co-Authored-By was not removed"; rm "$TMPFILE"; exit 1
fi

# Case 4: strips Cursor
printf "feat: my commit\n\nCo-Authored-By: Cursor <cursor@cursor.sh>\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
if grep -q "Co-Authored-By:.*[Cc]ursor" "$TMPFILE"; then
  echo "FAIL: Cursor Co-Authored-By was not removed"; rm "$TMPFILE"; exit 1
fi

# Case 5: preserves human Co-Authored-By lines
printf "feat: my commit\n\nCo-Authored-By: Alice <alice@example.com>\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
if ! grep -q "Co-Authored-By: Alice" "$TMPFILE"; then
  echo "FAIL: human Co-Authored-By line was removed"; rm "$TMPFILE"; exit 1
fi

# Case 6: no-op on clean messages
printf "feat: clean commit\n" > "$TMPFILE"
"$HOOK" "$TMPFILE"
CONTENT=$(cat "$TMPFILE")
if [ "$CONTENT" != "feat: clean commit" ]; then
  echo "FAIL: clean message was modified"; rm "$TMPFILE"; exit 1
fi

# Case 7: strips each AI credit line
for line in 'Generated by Codex' 'generated by claude code' '🤖 Generated with [Claude Code](https://claude.ai/code)' '_Generated using Cursor_' 'Generated by GPT-5' 'Co-Authored-By: Claude <noreply@anthropic.com>' 'Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>' 'Co-authored-by: devin-ai-integration[bot] <158243242+devin-ai-integration[bot]@users.noreply.github.com>'; do
  printf 'feat: x\n\n%s\n' "$line" > "$TMPFILE"; "$HOOK" "$TMPFILE"
  if [ "$(grep -c . "$TMPFILE")" != 1 ]; then
    echo "FAIL: not stripped: $line"; rm "$TMPFILE"; exit 1
  fi
done

# Case 8: keeps ordinary text and human co-authors, including names that contain or match a tool name
for line in 'fix: remove files generated by codex' 'The schema is generated by the Codex tool' 'Generated by protoc' 'Co-Authored-By: Alice <alice@example.com>' 'Co-Authored-By: Haider Ali <haider@example.com>' 'Co-Authored-By: Devin Smith <devin@example.com>' 'Co-Authored-By: Claude Monet <claude@example.com>' 'Co-Authored-By: Alice <alice@sourcegraph.com>'; do
  printf 'feat: x\n\n%s\n' "$line" > "$TMPFILE"; "$HOOK" "$TMPFILE"
  if ! grep -qF "$line" "$TMPFILE"; then
    echo "FAIL: wrongly stripped: $line"; rm "$TMPFILE"; exit 1
  fi
done

rm "$TMPFILE"
echo "All tests passed."
